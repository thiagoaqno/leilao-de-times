const { test, expect } = require("@playwright/test");

test("efeitos e música têm controles independentes na pausa", async ({ page }) => {
  const erros = [];
  page.on("pageerror", (e) => erros.push(String(e)));
  await page.goto("/cozinha/#debug");
  await page.locator("#hName").fill("Chef");
  await page.locator("#btnCreate").click();
  await page.waitForFunction(() => window.__cozinha?.Som.faixa === "lobby");
  expect(await page.evaluate(() => window.__cozinha.Som.audio.currentSrc)).toContain("/cozinha/musicas/lobby.mp3");
  await page.locator("#btnStart").click();
  await page.waitForFunction(() => window.__cozinha?.G.mesa?.fase === "jogo");
  await page.waitForFunction(() => window.__cozinha?.Som.faixa === "1");
  expect(await page.evaluate(() => window.__cozinha.Som.audio.currentSrc)).toContain("/cozinha/musicas/fase-1.mp3");
  await expect(page.locator("#hPed .ing").first()).toContainText("3×");
  await expect(page.locator("#hPed .ing").first()).toContainText("Cebola");
  if (process.env.COZINHA_FOTO_JOGO) await page.screenshot({ path: process.env.COZINHA_FOTO_JOGO });
  await page.keyboard.press("Escape");
  await expect(page.locator("#pause")).toBeVisible();
  if (process.env.COZINHA_FOTO) await page.screenshot({ path: process.env.COZINHA_FOTO, fullPage: true });
  await page.locator("#btnMus").click();
  await expect(page.locator("#mus")).toHaveValue("0");
  expect(await page.evaluate(() => window.__cozinha.Som.audio.paused)).toBe(true);
  await expect(page.locator("#vol")).toHaveValue("0.7");
  await page.locator("#btnFx").click();
  await expect(page.locator("#vol")).toHaveValue("0");
  await page.locator("#btnMus").click();
  await expect(page.locator("#mus")).toHaveValue("0.35");
  await page.waitForFunction(() => !window.__cozinha.Som.audio.paused);
  await page.reload();
  await expect(page.locator("#mus")).toHaveValue("0.35");
  await expect(page.locator("#vol")).toHaveValue("0");
  expect(erros).toEqual([]);
});
